import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const sqlPackageDirectory = path.resolve(scriptDirectory, '..');
const inputDirectory = path.join(
  sqlPackageDirectory,
  'backups',
  'dynamodb',
  'hat-tricks'
);
const outputDirectory = path.join(sqlPackageDirectory, 'generated');
const outputFile = path.join(outputDirectory, 'hat-tricks.sql');
const reportFile = path.join(outputDirectory, 'hat-tricks-report.json');
const rowsPerStatement = 100;

function requiredString(item, field, source) {
  const value = item?.[field]?.S;
  if (typeof value !== 'string' || value === '') {
    throw new Error(`${source}: missing ${field}.S`);
  }
  if (value.includes('\0')) {
    throw new Error(`${source}: ${field} contains a null byte`);
  }
  return value;
}

function requiredInteger(item, field, source) {
  const value = item?.[field]?.N;
  const number = Number(value);
  if (typeof value !== 'string' || !Number.isSafeInteger(number)) {
    throw new Error(`${source}: invalid ${field}.N`);
  }
  return number;
}

function validDate(value) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00Z`);
  return (
    !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value
  );
}

function parseHatTrick(line, source) {
  let record;
  try {
    record = JSON.parse(line);
  } catch {
    throw new Error(`${source}: invalid JSON`);
  }
  if (!record.Item) throw new Error(`${source}: missing Item`);

  const item = record.Item;
  const season = Number(requiredString(item, 'Season', source));
  const matchDate = requiredString(item, 'Date', source);
  const goals = requiredInteger(item, 'Goals', source);

  if (!Number.isSafeInteger(season) || season < 1800 || season > 2200) {
    throw new Error(`${source}: invalid Season ${season}`);
  }
  if (!validDate(matchDate)) {
    throw new Error(`${source}: invalid Date ${matchDate}`);
  }
  if (goals < 3) {
    throw new Error(`${source}: Goals must be at least 3`);
  }

  return {
    id: requiredString(item, 'id', source),
    season,
    matchDate,
    opposition: requiredString(item, 'Opposition', source),
    playerName: requiredString(item, 'Player', source),
    goals
  };
}

function sqlString(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function values(hatTrick) {
  return `(${[
    sqlString(hatTrick.id),
    hatTrick.season,
    sqlString(hatTrick.matchDate),
    sqlString(hatTrick.opposition),
    sqlString(hatTrick.playerName),
    hatTrick.goals
  ].join(', ')})`;
}

const files = (await readdir(inputDirectory))
  .filter((file) => file.endsWith('.json'))
  .sort();
if (files.length === 0) {
  throw new Error(`No DynamoDB JSON files found in ${inputDirectory}`);
}

const hatTricks = [];
const ids = new Set();
for (const file of files) {
  const contents = await readFile(path.join(inputDirectory, file), 'utf8');
  contents
    .split(/\r?\n/)
    .filter((line) => line.trim())
    .forEach((line, index) => {
      const source = `${file}:${index + 1}`;
      const hatTrick = parseHatTrick(line, source);
      if (ids.has(hatTrick.id)) {
        throw new Error(`${source}: duplicate hat-trick ID ${hatTrick.id}`);
      }
      ids.add(hatTrick.id);
      hatTricks.push(hatTrick);
    });
}

hatTricks.sort(
  (a, b) =>
    a.matchDate.localeCompare(b.matchDate) ||
    a.playerName.localeCompare(b.playerName) ||
    a.id.localeCompare(b.id)
);

const statements = [];
for (let index = 0; index < hatTricks.length; index += rowsPerStatement) {
  const batch = hatTricks.slice(index, index + rowsPerStatement);
  statements.push(`INSERT INTO HatTricks (
  id, season, match_date, opposition, player_name, goals
) VALUES
  ${batch.map(values).join(',\n  ')}
ON CONFLICT(id) DO UPDATE SET
  season = excluded.season,
  match_date = excluded.match_date,
  opposition = excluded.opposition,
  player_name = excluded.player_name,
  goals = excluded.goals;`);
}

const sql = `-- Generated by scripts/dynamodb-hat-tricks-to-d1.mjs
-- Source files: ${files.length}
-- Hat-trick records: ${hatTricks.length}
-- This file is idempotent: existing records with the same ID are updated.

${statements.join('\n\n')}
`;

await mkdir(outputDirectory, { recursive: true });
await Promise.all([
  writeFile(outputFile, sql, 'utf8'),
  writeFile(
    reportFile,
    `${JSON.stringify(
      { sourceFiles: files.length, records: hatTricks.length },
      null,
      2
    )}\n`,
    'utf8'
  )
]);

console.log(
  `Generated ${hatTricks.length} hat-trick records from ${files.length} files at ${outputFile}`
);
console.log(`Wrote migration report to ${reportFile}`);
