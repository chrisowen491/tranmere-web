import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const sqlPackageDirectory = path.resolve(scriptDirectory, '..');
const inputDirectory = path.join(
  sqlPackageDirectory,
  'backups',
  'dynamodb',
  'managers'
);
const outputDirectory = path.join(sqlPackageDirectory, 'generated');
const outputFile = path.join(outputDirectory, 'managers.sql');
const rowsPerStatement = 100;

function readAttribute(item, name, type, source, optional = false) {
  const attribute = item?.[name];
  if (optional && !attribute) return null;
  if (!attribute || typeof attribute[type] !== 'string') {
    throw new Error(`${source}: missing ${name}.${type}`);
  }
  return attribute[type];
}

function sqlString(value) {
  if (value === null) return 'NULL';
  if (value.includes('\0')) {
    throw new Error('D1 text values cannot contain null bytes');
  }
  return `'${value.replaceAll("'", "''")}'`;
}

function isValidDateValue(value, allowCurrent = false) {
  if (allowCurrent && /^(now|now\(\))$/i.test(value)) return true;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  return !Number.isNaN(Date.parse(`${value}T00:00:00Z`));
}

function parseManager(line, source) {
  let record;
  try {
    record = JSON.parse(line);
  } catch {
    throw new Error(`${source}: invalid JSON`);
  }

  const item = record.Item;
  const dateJoined = readAttribute(item, 'dateJoined', 'S', source);
  const dateLeft = readAttribute(item, 'dateLeft', 'S', source);

  if (!isValidDateValue(dateJoined)) {
    throw new Error(`${source}: invalid dateJoined ${dateJoined}`);
  }
  if (!isValidDateValue(dateLeft, true)) {
    throw new Error(`${source}: invalid dateLeft ${dateLeft}`);
  }

  return {
    id: readAttribute(item, 'id', 'S', source),
    name: readAttribute(item, 'name', 'S', source),
    dateJoined,
    dateLeft,
    programmePath: readAttribute(item, 'programmePath', 'S', source, true)
  };
}

function managerValues(manager) {
  return `(${[
    sqlString(manager.id),
    sqlString(manager.name),
    sqlString(manager.dateJoined),
    sqlString(manager.dateLeft),
    sqlString(manager.programmePath)
  ].join(', ')})`;
}

const files = (await readdir(inputDirectory))
  .filter((file) => file.endsWith('.json'))
  .sort();

if (files.length === 0) {
  throw new Error(`No DynamoDB JSON files found in ${inputDirectory}`);
}

const managers = [];
const ids = new Set();

for (const file of files) {
  const contents = await readFile(path.join(inputDirectory, file), 'utf8');
  const lines = contents.split(/\r?\n/).filter((line) => line.trim());

  lines.forEach((line, index) => {
    const source = `${file}:${index + 1}`;
    const manager = parseManager(line, source);
    if (ids.has(manager.id)) {
      throw new Error(`${source}: duplicate manager id ${manager.id}`);
    }
    ids.add(manager.id);
    managers.push(manager);
  });
}

managers.sort(
  (a, b) =>
    a.dateJoined.localeCompare(b.dateJoined) ||
    a.name.localeCompare(b.name) ||
    a.id.localeCompare(b.id)
);

const statements = [];
for (let index = 0; index < managers.length; index += rowsPerStatement) {
  const values = managers
    .slice(index, index + rowsPerStatement)
    .map(managerValues)
    .join(',\n  ');

  statements.push(`INSERT INTO Managers (
  id,
  name,
  date_joined,
  date_left,
  programme_path
) VALUES
  ${values}
ON CONFLICT(id) DO UPDATE SET
  name = excluded.name,
  date_joined = excluded.date_joined,
  date_left = excluded.date_left,
  programme_path = excluded.programme_path;`);
}

const sql = `-- Generated by scripts/dynamodb-managers-to-d1.mjs
-- Source files: ${files.length}
-- Manager records: ${managers.length}
-- This file is idempotent: existing records with the same id are updated.

${statements.join('\n\n')}
`;

await mkdir(outputDirectory, { recursive: true });
await writeFile(outputFile, sql, 'utf8');

console.log(
  `Generated ${managers.length} managers from ${files.length} files at ${outputFile}`
);
