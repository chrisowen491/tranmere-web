import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const sqlPackageDirectory = path.resolve(scriptDirectory, '..');
const inputDirectory = path.join(
  sqlPackageDirectory,
  'backups',
  'dynamodb',
  'reports'
);
const outputDirectory = path.join(sqlPackageDirectory, 'generated');
const outputFile = path.join(outputDirectory, 'match-reports.sql');
const reportFile = path.join(outputDirectory, 'match-reports-report.json');
const rowsPerStatement = 25;

function stringAttribute(item, field, source) {
  const value = item?.[field]?.S;
  if (typeof value !== 'string') {
    throw new Error(`${source}: missing ${field}.S`);
  }
  if (value.includes('\0')) {
    throw new Error(`${source}: ${field} contains a null byte`);
  }
  return value;
}

function requiredString(item, field, source) {
  const value = stringAttribute(item, field, source);
  if (value === '') throw new Error(`${source}: missing ${field}.S`);
  return value;
}

function validDate(value) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00Z`);
  return (
    !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value
  );
}

function parseReport(line, source) {
  let record;
  try {
    record = JSON.parse(line);
  } catch {
    throw new Error(`${source}: invalid JSON`);
  }
  if (!record.Item) throw new Error(`${source}: missing Item`);

  const matchDate = requiredString(record.Item, 'day', source);
  if (!validDate(matchDate)) {
    throw new Error(`${source}: invalid day ${matchDate}`);
  }

  return {
    matchDate,
    report: stringAttribute(record.Item, 'report', source)
  };
}

function sqlString(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

const files = (await readdir(inputDirectory))
  .filter((file) => file.endsWith('.json'))
  .sort();
if (files.length === 0) {
  throw new Error(`No DynamoDB JSON files found in ${inputDirectory}`);
}

const reports = [];
const dates = new Set();
for (const file of files) {
  const contents = await readFile(path.join(inputDirectory, file), 'utf8');
  contents
    .split(/\r?\n/)
    .filter((line) => line.trim())
    .forEach((line, index) => {
      const source = `${file}:${index + 1}`;
      const report = parseReport(line, source);
      if (dates.has(report.matchDate)) {
        throw new Error(
          `${source}: duplicate match report date ${report.matchDate}`
        );
      }
      dates.add(report.matchDate);
      reports.push(report);
    });
}

reports.sort((a, b) => a.matchDate.localeCompare(b.matchDate));

const statements = [];
for (let index = 0; index < reports.length; index += rowsPerStatement) {
  const values = reports
    .slice(index, index + rowsPerStatement)
    .map(
      (report) =>
        `(${sqlString(report.matchDate)}, ${sqlString(report.report)})`
    )
    .join(',\n  ');
  statements.push(`INSERT INTO MatchReports (match_date, report) VALUES
  ${values}
ON CONFLICT(match_date) DO UPDATE SET
  report = excluded.report;`);
}

const sql = `-- Generated by scripts/dynamodb-match-reports-to-d1.mjs
-- Source files: ${files.length}
-- Match reports: ${reports.length}
-- This file is idempotent: existing reports for the same match date are updated.

${statements.join('\n\n')}
`;

await mkdir(outputDirectory, { recursive: true });
await Promise.all([
  writeFile(outputFile, sql, 'utf8'),
  writeFile(
    reportFile,
    `${JSON.stringify(
      { sourceFiles: files.length, records: reports.length },
      null,
      2
    )}\n`,
    'utf8'
  )
]);

console.log(
  `Generated ${reports.length} match reports from ${files.length} files at ${outputFile}`
);
console.log(`Wrote migration report to ${reportFile}`);
