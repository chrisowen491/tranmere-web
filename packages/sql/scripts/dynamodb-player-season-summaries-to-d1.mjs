import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const sqlPackageDirectory = path.resolve(scriptDirectory, '..');
const inputDirectory = path.join(
  sqlPackageDirectory,
  'backups',
  'dynamodb',
  'player-season-summary'
);
const outputDirectory = path.join(sqlPackageDirectory, 'generated');
const outputFile = path.join(outputDirectory, 'player-season-summaries.sql');
const reportFile = path.join(
  outputDirectory,
  'player-season-summaries-report.json'
);
const rowsPerStatement = 100;

function requiredString(item, field, source) {
  const value = item?.[field]?.S;
  if (typeof value !== 'string' || value === '') {
    throw new Error(`${source}: missing ${field}.S`);
  }
  if (value.includes('\0')) {
    throw new Error(`${source}: ${field} contains a null byte`);
  }
  return value;
}

function requiredInteger(item, field, source) {
  const value = item?.[field]?.N;
  const number = Number(value);
  if (
    typeof value !== 'string' ||
    !Number.isSafeInteger(number) ||
    number < 0
  ) {
    throw new Error(`${source}: invalid ${field}.N`);
  }
  return number;
}

function parseSummary(line, source) {
  let record;
  try {
    record = JSON.parse(line);
  } catch {
    throw new Error(`${source}: invalid JSON`);
  }
  if (!record.Item) throw new Error(`${source}: missing Item`);

  const item = record.Item;
  const season = requiredString(item, 'Season', source);
  if (season !== 'TOTAL' && !/^(18|19|20|21)\d{2}$/.test(season)) {
    throw new Error(`${source}: invalid Season ${season}`);
  }

  return {
    season,
    playerName: requiredString(item, 'Player', source),
    appearances: requiredInteger(item, 'Apps', source),
    starts: requiredInteger(item, 'starts', source),
    substituteAppearances: requiredInteger(item, 'subs', source),
    goals: requiredInteger(item, 'goals', source),
    assists: requiredInteger(item, 'assists', source),
    yellowCards: requiredInteger(item, 'yellow', source),
    redCards: requiredInteger(item, 'red', source),
    freeKicks: requiredInteger(item, 'freekicks', source),
    penalties: requiredInteger(item, 'penalties', source),
    headers: requiredInteger(item, 'headers', source)
  };
}

function sqlString(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function values(summary) {
  return `(${[
    sqlString(summary.season),
    sqlString(summary.playerName),
    summary.appearances,
    summary.starts,
    summary.substituteAppearances,
    summary.goals,
    summary.assists,
    summary.yellowCards,
    summary.redCards,
    summary.freeKicks,
    summary.penalties,
    summary.headers
  ].join(', ')})`;
}

const files = (await readdir(inputDirectory))
  .filter((file) => file.endsWith('.json'))
  .sort();
if (files.length === 0) {
  throw new Error(`No DynamoDB JSON files found in ${inputDirectory}`);
}

const summaries = [];
const keys = new Set();
for (const file of files) {
  const contents = await readFile(path.join(inputDirectory, file), 'utf8');
  contents
    .split(/\r?\n/)
    .filter((line) => line.trim())
    .forEach((line, index) => {
      const source = `${file}:${index + 1}`;
      const summary = parseSummary(line, source);
      const key = `${summary.season}\0${summary.playerName}`;
      if (keys.has(key)) {
        throw new Error(
          `${source}: duplicate player-season summary for ${summary.playerName} in ${summary.season}`
        );
      }
      keys.add(key);
      summaries.push(summary);
    });
}

summaries.sort(
  (a, b) =>
    a.season.localeCompare(b.season) || a.playerName.localeCompare(b.playerName)
);

const statements = [];
for (let index = 0; index < summaries.length; index += rowsPerStatement) {
  const batch = summaries.slice(index, index + rowsPerStatement);
  statements.push(`INSERT INTO PlayerSeasonSummaries (
  season, player_name, appearances, starts, substitute_appearances, goals,
  assists, yellow_cards, red_cards, free_kicks, penalties, headers
) VALUES
  ${batch.map(values).join(',\n  ')}
ON CONFLICT(season, player_name) DO UPDATE SET
  appearances = excluded.appearances,
  starts = excluded.starts,
  substitute_appearances = excluded.substitute_appearances,
  goals = excluded.goals,
  assists = excluded.assists,
  yellow_cards = excluded.yellow_cards,
  red_cards = excluded.red_cards,
  free_kicks = excluded.free_kicks,
  penalties = excluded.penalties,
  headers = excluded.headers;`);
}

const sql = `-- Generated by scripts/dynamodb-player-season-summaries-to-d1.mjs
-- Source files: ${files.length}
-- Player-season summary records: ${summaries.length}
-- This file is idempotent: existing records with the same player and season are updated.

${statements.join('\n\n')}
`;

await mkdir(outputDirectory, { recursive: true });
await Promise.all([
  writeFile(outputFile, sql, 'utf8'),
  writeFile(
    reportFile,
    `${JSON.stringify(
      { sourceFiles: files.length, records: summaries.length },
      null,
      2
    )}\n`,
    'utf8'
  )
]);

console.log(
  `Generated ${summaries.length} player-season summaries from ${files.length} files at ${outputFile}`
);
console.log(`Wrote migration report to ${reportFile}`);
