import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const sqlPackageDirectory = path.resolve(scriptDirectory, "..");
const inputDirectory = path.join(
  sqlPackageDirectory,
  "backups",
  "dynamodb",
  "transfers",
);
const outputDirectory = path.join(sqlPackageDirectory, "generated");
const outputFile = path.join(outputDirectory, "transfers.sql");
const rowsPerStatement = 100;

function readAttribute(item, name, type, source) {
  const attribute = item?.[name];
  if (!attribute || typeof attribute[type] !== "string") {
    throw new Error(`${source}: missing ${name}.${type}`);
  }
  return attribute[type];
}

function sqlString(value) {
  if (value.includes("\0")) {
    throw new Error("D1 text values cannot contain null bytes");
  }
  return `'${value.replaceAll("'", "''")}'`;
}

function parseTransfer(line, source) {
  let record;
  try {
    record = JSON.parse(line);
  } catch {
    throw new Error(`${source}: invalid JSON`);
  }

  const item = record.Item;
  const season = Number(readAttribute(item, "season", "N", source));
  const cost = Number(readAttribute(item, "cost", "N", source));

  if (!Number.isSafeInteger(season) || season < 1800 || season > 2200) {
    throw new Error(`${source}: invalid season ${season}`);
  }
  if (!Number.isSafeInteger(cost) || cost < 0) {
    throw new Error(`${source}: invalid cost ${cost}`);
  }

  return {
    id: readAttribute(item, "id", "S", source),
    playerName: readAttribute(item, "name", "S", source),
    season,
    fromClub: readAttribute(item, "from", "S", source),
    toClub: readAttribute(item, "to", "S", source),
    feeDescription: readAttribute(item, "value", "S", source),
    cost,
  };
}

function transferValues(transfer) {
  return `(${[
    sqlString(transfer.id),
    sqlString(transfer.playerName),
    transfer.season,
    sqlString(transfer.fromClub),
    sqlString(transfer.toClub),
    sqlString(transfer.feeDescription),
    transfer.cost,
  ].join(", ")})`;
}

const files = (await readdir(inputDirectory))
  .filter((file) => file.endsWith(".json"))
  .sort();

if (files.length === 0) {
  throw new Error(`No DynamoDB JSON files found in ${inputDirectory}`);
}

const transfers = [];
const ids = new Set();

for (const file of files) {
  const contents = await readFile(path.join(inputDirectory, file), "utf8");
  const lines = contents.split(/\r?\n/).filter((line) => line.trim());

  lines.forEach((line, index) => {
    const source = `${file}:${index + 1}`;
    const transfer = parseTransfer(line, source);
    if (ids.has(transfer.id)) {
      throw new Error(`${source}: duplicate transfer id ${transfer.id}`);
    }
    ids.add(transfer.id);
    transfers.push(transfer);
  });
}

transfers.sort(
  (a, b) =>
    a.season - b.season ||
    a.playerName.localeCompare(b.playerName) ||
    a.id.localeCompare(b.id),
);

const statements = [];
for (let index = 0; index < transfers.length; index += rowsPerStatement) {
  const values = transfers
    .slice(index, index + rowsPerStatement)
    .map(transferValues)
    .join(",\n  ");

  statements.push(`INSERT INTO Transfers (
  id,
  player_name,
  season,
  from_club,
  to_club,
  fee_description,
  cost
) VALUES
  ${values}
ON CONFLICT(id) DO UPDATE SET
  player_name = excluded.player_name,
  season = excluded.season,
  from_club = excluded.from_club,
  to_club = excluded.to_club,
  fee_description = excluded.fee_description,
  cost = excluded.cost;`);
}

const sql = `-- Generated by scripts/dynamodb-transfers-to-d1.mjs
-- Source files: ${files.length}
-- Transfer records: ${transfers.length}
-- This file is idempotent: existing records with the same id are updated.

${statements.join("\n\n")}
`;

await mkdir(outputDirectory, { recursive: true });
await writeFile(outputFile, sql, "utf8");

console.log(
  `Generated ${transfers.length} transfers from ${files.length} files at ${outputFile}`,
);

